// Retires the BoardHistory collection (ticket 12): past boards now come from
// the Portal's Board Archives. Deploys run migrations automatically, so each
// year is first flattened into board_history_archive, with every person's name
// and position as they are now, for the one-time copy into Board Archives
// (scripts/export-board-history.ts). Drop the archive once that copy is done.
//
// Payload stores array rows with _order = index + 1, and relationships inside
// them under the path "groups.<index>.members".
//
// Generated by `payload migrate:create`, then reordered: the generated SQL
// dropped the tables with CASCADE before dropping the constraint that
// referenced them, which fails because CASCADE has already removed it.
export async function up({ db, payload, req }: MigrateUpArgs): Promise<void> {
  await db.execute(sql`
  CREATE TABLE "board_history_archive" AS
    SELECT
      h."academic_year", g."_order" AS "group_order", g."group_name",
      r."order" AS "member_order", p."name" AS "person_name",
      p."position" AS "person_position", now() AS "archived_at"
    FROM "board_history" h
    JOIN "board_history_groups" g ON g."_parent_id" = h."id"
    LEFT JOIN "board_history_rels" r
      ON r."parent_id" = h."id"
      AND r."path" = 'groups.' || (g."_order" - 1) || '.members'
    LEFT JOIN "people" p ON p."id" = r."people_id";
  DELETE FROM "payload_locked_documents" WHERE "id" IN (
    SELECT "parent_id" FROM "payload_locked_documents_rels" WHERE "board_history_id" IS NOT NULL
  );
  ALTER TABLE "payload_locked_documents_rels" DROP CONSTRAINT "payload_locked_documents_rels_board_history_fk";
  DROP INDEX "payload_locked_documents_rels_board_history_id_idx";
  ALTER TABLE "payload_locked_documents_rels" DROP COLUMN "board_history_id";
  ALTER TABLE "board_history_groups" DISABLE ROW LEVEL SECURITY;
  ALTER TABLE "board_history" DISABLE ROW LEVEL SECURITY;
  ALTER TABLE "board_history_rels" DISABLE ROW LEVEL SECURITY;
  DROP TABLE "board_history_groups" CASCADE;
  DROP TABLE "board_history_rels" CASCADE;
  DROP TABLE "board_history" CASCADE;`)
}

